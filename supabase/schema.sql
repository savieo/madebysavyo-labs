values ('customer-files','customer-files',false,52428800)
on conflict (id) do nothing;

drop policy if exists customer_files_admin_read on storage.objects;
create policy customer_files_admin_read on storage.objects for select to authenticated using (bucket_id = 'customer-files' and public.is_admin());
drop policy if exists customer_files_admin_insert on storage.objects;
create policy customer_files_admin_insert on storage.objects for insert to authenticated with check (bucket_id = 'customer-files' and public.is_admin());
drop policy if exists customer_files_admin_update on storage.objects;
create policy customer_files_admin_update on storage.objects for update to authenticated using (bucket_id = 'customer-files' and public.is_admin()) with check (bucket_id = 'customer-files' and public.is_admin());
drop policy if exists customer_files_admin_delete on storage.objects;
create policy customer_files_admin_delete on storage.objects for delete to authenticated using (bucket_id = 'customer-files' and public.is_admin());

create index if not exists enquiries_status_created_idx on public.enquiries(status, created_at desc);
