-- MadeBySavyo Labs operational database
-- Run in Supabase SQL Editor. Operational records are private by default.
create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admin_users au where au.user_id = auth.uid()); $$;

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null,
  phone text, company text, notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists customers_email_lower_uidx on public.customers (lower(email));

create table if not exists public.enquiries (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid references public.customers(id) on delete set null,
  enquiry_number bigint generated by default as identity unique,
  source text not null default 'website',
  request_type text not null default 'On-demand printing',
  status text not null default 'new' check (status in ('new','reviewing','quote_draft','quote_sent','approved','declined','converted','closed')),
  quantity integer not null default 1 check (quantity > 0),
  model_link text, material_preference text, colour_preference text,
  project_details text, deadline text, uploaded_file_names text,
  files_in_email boolean not null default false,
  source_hash text unique,
  source_payload jsonb not null default '{}'::jsonb,
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.enquiry_files (
  id uuid primary key default gen_random_uuid(),
  enquiry_id uuid not null references public.enquiries(id) on delete cascade,
  file_name text not null, content_type text, file_size_bytes bigint,
  storage_path text,
  source text not null default 'email' check (source in ('email','storage','external')),
  created_at timestamptz not null default now()
);

create table if not exists public.quotes (
  id uuid primary key default gen_random_uuid(),
  enquiry_id uuid not null references public.enquiries(id) on delete cascade,
  quote_number bigint generated by default as identity unique,
  status text not null default 'draft' check (status in ('draft','sent','approved','declined','expired')),
  currency text not null default 'CAD',
  amount numeric(10,2) not null default 0 check (amount >= 0),
  material_cost numeric(10,2) not null default 0,
  machine_cost numeric(10,2) not null default 0,
  design_cost numeric(10,2) not null default 0,
  finishing_cost numeric(10,2) not null default 0,
  discount numeric(10,2) not null default 0,
  notes text, valid_until date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  enquiry_id uuid references public.enquiries(id) on delete set null,
  quote_id uuid references public.quotes(id) on delete set null,
  customer_id uuid references public.customers(id) on delete set null,
  status text not null default 'queued' check (status in ('queued','preparing','printing','quality_check','ready_for_pickup','delivered','cancelled')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','deposit_paid','paid','refunded','not_required')),
  material text, colour text,
  quantity integer not null default 1 check (quantity > 0),
  estimated_grams numeric(10,2), actual_grams numeric(10,2),
  estimated_hours numeric(8,2), actual_hours numeric(8,2),
  due_date date, total_amount numeric(10,2) not null default 0,
  notes text, started_at timestamptz, completed_at timestamptz, delivered_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid references public.orders(id) on delete set null,
  customer_id uuid references public.customers(id) on delete set null,
  amount numeric(10,2) not null check (amount >= 0),
  currency text not null default 'CAD',
  method text not null default 'manual' check (method in ('cash','etransfer','stripe','other','manual')),
  status text not null default 'received' check (status in ('pending','received','failed','refunded')),
  reference text, paid_at timestamptz, notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.filament_inventory (
  id uuid primary key default gen_random_uuid(),
  material text not null, brand text, colour text not null,
  spool_weight_g numeric(10,2) not null default 1000,
  remaining_weight_g numeric(10,2) not null default 1000,
  cost_per_kg numeric(10,2), location text,
  is_active boolean not null default true, notes text,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  check (remaining_weight_g >= 0 and spool_weight_g > 0)
);

create table if not exists public.model_catalog (
  id uuid primary key default gen_random_uuid(),
  title text not null, creator text, source_platform text, source_url text not null,
  file_format text, licence text, category text, description text, thumbnail_url text,
  commercial_use_verified boolean not null default false,
  attribution_required boolean not null default true,
  review_status text not null default 'needs_review' check (review_status in ('needs_review','verified','blocked')),
  is_published boolean not null default false, featured boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text not null, order_reference text,
  rating integer not null check (rating between 1 and 5),
  review_text text not null, photo_file_names text,
  permission_to_feature boolean not null default false,
  moderation_status text not null default 'pending' check (moderation_status in ('pending','approved','rejected')),
  published_at timestamptz, created_at timestamptz not null default now()
);

create table if not exists public.project_stories (
  id uuid primary key default gen_random_uuid(),
  title text not null, category text, summary text, material text,
  image_url text, video_url text,
  customer_permission boolean not null default false,
  is_published boolean not null default false, sort_order integer not null default 100,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.enquiry_events (
  id uuid primary key default gen_random_uuid(),
  enquiry_id uuid not null references public.enquiries(id) on delete cascade,
  event_type text not null, event_note text, created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

do $$
declare t text;
begin
  foreach t in array array['customers','enquiries','quotes','orders','filament_inventory','model_catalog','project_stories'] loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
  end loop;
end $$;

alter table public.admin_users enable row level security;
drop policy if exists admin_users_read_self on public.admin_users;
create policy admin_users_read_self on public.admin_users for select to authenticated using (user_id = auth.uid());

do $$
declare t text;
begin
  foreach t in array array['customers','enquiries','enquiry_files','quotes','orders','payments','filament_inventory','model_catalog','reviews','project_stories','enquiry_events'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists admin_all on public.%I', t);
    execute format('create policy admin_all on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

drop policy if exists public_read_published_models on public.model_catalog;
create policy public_read_published_models on public.model_catalog for select to anon, authenticated
using (is_published = true and review_status = 'verified');

drop policy if exists public_read_approved_reviews on public.reviews;
create policy public_read_approved_reviews on public.reviews for select to anon, authenticated
using (moderation_status = 'approved');

drop policy if exists public_read_published_stories on public.project_stories;
create policy public_read_published_stories on public.project_stories for select to anon, authenticated
using (is_published = true and customer_permission = true);

